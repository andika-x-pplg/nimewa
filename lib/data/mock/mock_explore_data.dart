List<AnimeItem> getExploreAnime({
  required String filter,
  String? genre,
  String? query,
  int limit = 20,
  int offset = 0,
}) {
  List<AnimeItem> pool;

  if (query != null && query.isNotEmpty) {
    final cleanQuery = query.toLowerCase().trim();
    pool = allCatalogAnime.where((item) {
      return item.title.toLowerCase().contains(cleanQuery) ||
          item.japaneseTitle.toLowerCase().contains(cleanQuery) ||
          item.genres.any((g) => g.toLowerCase().contains(cleanQuery));
    }).toList();
  } else if (genre != null && genre != 'Semua' && genre.isNotEmpty) {
    pool = allCatalogAnime.where((item) => item.genres.contains(genre)).toList();
  } else {
    switch (filter) {
      case 'latest':
        pool = [...latestAnimeList];
        break;
      case 'top_rated':
        pool = [...topRatedAnimeList];
        break;
      case 'popular':
      default:
        pool = [...popularAnimeList];
        break;
    }
  }

  if (offset >= pool.length) return [];
  return pool.skip(offset).take(limit).toList();
}
